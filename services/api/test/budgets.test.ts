import { beforeAll, afterAll, beforeEach, afterEach, it, expect, vi } from 'vitest';
import { nativeFixture } from './fixtures/native-ledger.js';
import { NATIVE_FINANCIAL_PLAN_SCHEMA_STATEMENTS, NATIVE_FINANCIAL_PLAN_TABLES } from '../../ledger/src/dsql/financial-plan-schema.js';
import type { SqlClient, TransactionPool } from '../../ledger/src/dsql/projection.js';
const harness = vi.hoisted(() => ({ pool: undefined as unknown as SqlClient & TransactionPool }));
vi.mock('../src/http/clients.js', () => ({ rawSourceBucketName: 'test-evidence', s3: { send: vi.fn() } }));
vi.mock('../../ledger/src/dsql/connection.js', () => ({ createPool: () => harness.pool }));
const { runAgentTool } = await import('../src/agent/tools.js');
const { runFinancialWriteTool } = await import('../src/agent/financial-write-tools.js');
const { getFinancialWriteStatus } = await import('../src/financial-plans/service.js');
let fixture: Awaited<ReturnType<typeof nativeFixture>>;
const input = { action: 'set_recurring', month: '2026-11', totalMxnMinor: 10000, allocations: [{ categoryId: 'food', amountMxnMinor: 8000 }] };
const preview = async (args: Record<string, unknown>) => await runFinancialWriteTool('owner', 'preview_budget_change', args) as { operationId: string; after: { id: string; revision: number } };
const apply = async (id: string) => await runFinancialWriteTool('owner', 'apply_budget_change', { operationId: id });
const status = async (month = '2026-11') => await runAgentTool('owner', 'get_budget_status', { month }) as Record<string, any>;
beforeAll(async () => {
  fixture = await nativeFixture();
  for (const statement of NATIVE_FINANCIAL_PLAN_SCHEMA_STATEMENTS) await fixture.sql.query(statement);
  harness.pool = fixture.pool;
  await fixture.sql.query("INSERT INTO olbia.spend_categories VALUES ('food','Food',0),('fun','Entertainment',1) ON CONFLICT DO NOTHING");
}, 30_000);
afterAll(async () => { await fixture.sql.close(); });
beforeEach(async () => {
  vi.useFakeTimers({ toFake: ['Date'] }); vi.setSystemTime(new Date('2026-11-18T18:00:00Z'));
  await fixture.sql.exec(`TRUNCATE ${NATIVE_FINANCIAL_PLAN_TABLES.map(t => `olbia.${t}`).join(',')}`);
  await fixture.sql.query("UPDATE olbia.runtime_state SET mode='sql' WHERE id='storage'");
});
afterEach(() => { vi.useRealTimers(); });
it('MCP preview/apply is atomic/idempotent, resolves overrides, reallocates and preserves recurring history', async () => {
  const op = await preview(input);
  expect((await fixture.sql.query('SELECT id FROM olbia.spending_budgets')).rows).toEqual([]);
  const receipt = await apply(op.operationId);
  expect(await apply(op.operationId)).toEqual(receipt);
  expect(await status()).toMatchObject({ configured: true, budget: { id: op.after.id, revision: 1 }, unallocatedMxnMinor: 2000 });
  await expect(runAgentTool('other', 'list_budgets', {})).resolves.toMatchObject({ budgets: [] });
  await expect(runFinancialWriteTool('other', 'apply_budget_change', { operationId: op.operationId })).rejects.toThrow(/no encontrada/);
  const override = await preview({ action: 'set_override', month: '2026-12', totalMxnMinor: 6000, allocations: [{ categoryId: 'food', amountMxnMinor: 6000 }] });
  await apply(override.operationId);
  expect(await status('2026-12')).toMatchObject({ budget: { scope: 'override', totalMxnMinor: 6000 } });
  expect(await status('2027-01')).toMatchObject({ budget: { scope: 'recurring', totalMxnMinor: 10000 } });
  const move = await preview({ action: 'reallocate', entityId: op.after.id, expectedRevision: 1, month: '2026-12', fromCategoryId: 'food', toCategoryId: 'fun', amountMxnMinor: 1000 });
  await apply(move.operationId);
  expect(await status()).toMatchObject({ budget: { revision: 1, allocations: [{ categoryId: 'food', amountMxnMinor: 8000 }] } });
  expect(await status('2027-01')).toMatchObject({ budget: { revision: 1, totalMxnMinor: 10000, allocations: [{ categoryId: 'food', amountMxnMinor: 7000 }, { categoryId: 'fun', amountMxnMinor: 1000 }] } });
  const archive = await preview({ action: 'archive', entityId: move.after.id, expectedRevision: 1, month: '2027-01' }); await apply(archive.operationId);
  expect(await status('2027-01')).toMatchObject({ configured: false });
  const restore = await preview({ action: 'restore', entityId: archive.after.id, expectedRevision: 1 }); await apply(restore.operationId);
  expect(await status('2027-01')).toMatchObject({ configured: true });
  const history = await runAgentTool('owner', 'get_budget_history', { fromMonth: '2026-11', toMonth: '2027-01' }) as Record<string, any>;
  expect(history.months).toHaveLength(3);
  expect(history.latestChangeReferences.length).toBe(5);
});
it('MCP exclusions preserve actual spending, simulation is read-only, and stale/category/month conflicts do not apply', async () => {
  const setup = await preview(input); await apply(setup.operationId);
  const id = await fixture.create({ amount: { amountMinor: 3000, currency: 'MXN' }, categoryId: 'food', occurredAt: '2026-11-17T18:00:00Z' });
  const exclusion = await preview({ action: 'exclude_movement', month: '2026-11', movementId: id, reason: 'Extraordinary travel' });
  await apply(exclusion.operationId);
  expect(await status()).toMatchObject({ grossSpentMxnMinor: 3000, countedSpentMxnMinor: 0, excludedSpentMxnMinor: 3000 });
  const before = (await fixture.sql.query('SELECT * FROM olbia.financial_write_operations')).rows;
  const simulation = await runAgentTool('owner', 'simulate_budget_purchase', { month: '2026-11', amountMxnMinor: 2000, categoryId: 'food' });
  expect(simulation).toMatchObject({ readOnly: true, after: { countedSpentMxnMinor: 2000, remainingMxnMinor: 8000, categoryRemainingMxnMinor: 6000 } });
  expect((await fixture.sql.query('SELECT * FROM olbia.financial_write_operations')).rows).toEqual(before);
  const include = await preview({ action: 'include_movement', entityId: exclusion.after.id, expectedRevision: 1, reason: 'Operating expense after review' });
  await apply(include.operationId);
  expect(await status()).toMatchObject({ grossSpentMxnMinor: 3000, countedSpentMxnMinor: 3000 });
  const first = await preview({ action: 'set_recurring', entityId: setup.after.id, expectedRevision: 1, totalMxnMinor: 11000 });
  const stale = await preview({ action: 'archive', entityId: setup.after.id, expectedRevision: 1 });
  await apply(first.operationId);
  await expect(apply(stale.operationId)).rejects.toThrow(/cambió/);
  expect(await getFinancialWriteStatus('owner', stale.operationId)).toMatchObject({ status: 'failed' });
  await expect(preview({ action: 'set_recurring', month: '2026-10', totalMxnMinor: 100 })).rejects.toThrow(/cerrados/);
  const historical = await preview({ action: 'set_override', month: '2026-10', totalMxnMinor: 100 }); await apply(historical.operationId);
  expect(await status('2026-10')).toMatchObject({ configured: true, budget: { scope: 'override', totalMxnMinor: 100 } });
  const expiry = await preview({ action: 'archive', entityId: setup.after.id, expectedRevision: 2 });
  vi.setSystemTime(new Date('2026-11-18T18:16:00Z'));
  await expect(apply(expiry.operationId)).rejects.toThrow(/expiró/);
});
